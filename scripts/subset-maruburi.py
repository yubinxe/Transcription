"""Split MaruBuri (OFL-1.1) into two unicode-range subsets.

core: ASCII, Latin-1 punctuation, general punctuation, KS X 1001 2,350 Hangul.
ext:  every other Hangul syllable — fetched by the browser only when needed.
Run: python3 scripts/subset-maruburi.py
"""
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont

SRC = Path("node_modules/@kfonts/maruburi/src")
OUT = Path("public/fonts/maruburi")
WEIGHTS = {"Regular": 400, "SemiBold": 600}

ks = set()
for b1 in range(0xB0, 0xC9):
    for b2 in range(0xA1, 0xFF):
        try:
            ks.add(ord(bytes([b1, b2]).decode("euc-kr")))
        except UnicodeDecodeError:
            pass
ks = {c for c in ks if 0xAC00 <= c <= 0xD7A3}
base = set(range(0x20, 0x7F)) | set(range(0xA0, 0x100)) | set(range(0x2010, 0x2070)) | {0x3001, 0x3002, 0x300C, 0x300D, 0x300E, 0x300F, 0x00B7, 0x2026}
core = base | ks
ext = set(range(0xAC00, 0xD7A4)) - ks

def ranges(cps):
    cps = sorted(cps); out = []; start = prev = cps[0]
    for c in cps[1:]:
        if c == prev + 1:
            prev = c; continue
        out.append((start, prev)); start = prev = c
    out.append((start, prev))
    return ", ".join(f"U+{a:04X}" if a == b else f"U+{a:04X}-{b:04X}" for a, b in out)

css = ["/* MaruBuri — Naver, SIL Open Font License 1.1. Generated by scripts/subset-maruburi.py */"]
for name, weight in WEIGHTS.items():
    cmap = TTFont(SRC / f"MaruBuri-{name}.ttf").getBestCmap()
    for part, cps in (("core", core), ("ext", ext)):
        cps = {c for c in cps if c in cmap}
        opts = subset.Options(); opts.flavor = "woff2"; opts.layout_features = ["*"]; opts.name_IDs = ["*"]
        font = TTFont(SRC / f"MaruBuri-{name}.ttf")
        s = subset.Subsetter(opts); s.populate(unicodes=cps); s.subset(font)
        fn = f"MaruBuri-{name}-{part}.woff2"
        font.flavor = "woff2"; font.save(OUT / fn)
        css.append(f"@font-face{{font-family:'MaruBuri';font-style:normal;font-weight:{weight};font-display:swap;src:url('/fonts/maruburi/{fn}') format('woff2');unicode-range:{ranges(cps)};}}")
(OUT / "maruburi.css").write_text("\n".join(css) + "\n")
print("ok")
